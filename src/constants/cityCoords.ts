/** Estimated driving minutes between two points: straight line × 1.35, at 60 km/h, plus 10 min to park and unload. */
export function driveMinutes(a: readonly [number, number], b: readonly [number, number]): number {
  const r = Math.PI / 180;
  const dLat = (b[0] - a[0]) * r, dLon = (b[1] - a[1]) * r;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a[0] * r) * Math.cos(b[0] * r) * Math.sin(dLon / 2) ** 2;
  const km = 2 * 6371 * Math.asin(Math.sqrt(h)) * 1.35;
  return Math.round(km) + 10;
}
